"""
scripts/generate_synthea_sample.py

Generates a deterministic Synthea-structured synthetic development sample for CP-03.
Creates patients.csv, encounters.csv, and observations.csv containing 60 longitudinal patients
spanning encounters across 2021-2024 with standard LOINC codes.
Provenance Notice: Locally generated synthetic data conforming to Synthea's CSV schema
(not generated by the official Synthea Java generator or external Synthea distribution).
"""

from __future__ import annotations

import csv
import random
import uuid
from pathlib import Path


def generate_synthea_sample(output_dir: Path, n_patients: int = 60, seed: int = 42) -> None:
    random.seed(seed)
    output_dir.mkdir(parents=True, exist_ok=True)

    patients_file = output_dir / "patients.csv"
    encounters_file = output_dir / "encounters.csv"
    observations_file = output_dir / "observations.csv"

    # Pre-defined test configurations (LOINC, Description, Unit, Normal Mean, Trend std)
    lab_definitions = [
        {"code": "2089-1", "desc": "Low Density Lipoprotein Cholesterol", "unit": "mg/dL", "mean": 120.0, "std": 20.0, "type": "numeric"},
        {"code": "2085-9", "desc": "High Density Lipoprotein Cholesterol", "unit": "mg/dL", "mean": 50.0, "std": 10.0, "type": "numeric"},
        {"code": "2093-3", "desc": "Total Cholesterol", "unit": "mg/dL", "mean": 195.0, "std": 25.0, "type": "numeric"},
        {"code": "2571-8", "desc": "Triglycerides", "unit": "mg/dL", "mean": 140.0, "std": 30.0, "type": "numeric"},
        {"code": "718-7", "desc": "Hemoglobin [Mass/volume] in Blood", "unit": "g/dL", "mean": 14.2, "std": 1.5, "type": "numeric"},
        {"code": "6690-2", "desc": "Leukocytes [#/volume] in Blood by Automated count", "unit": "/uL", "mean": 6500.0, "std": 1200.0, "type": "numeric"},
        {"code": "777-3", "desc": "Platelets [#/volume] in Blood by Automated count", "unit": "/uL", "mean": 240000.0, "std": 45000.0, "type": "numeric"},
        {"code": "4548-4", "desc": "Hemoglobin A1c/Hemoglobin.total in Blood", "unit": "%", "mean": 5.8, "std": 0.8, "type": "numeric"},
        {"code": "2345-7", "desc": "Glucose [Mass/volume] in Serum or Plasma", "unit": "mg/dL", "mean": 95.0, "std": 15.0, "type": "numeric"},
        {"code": "2160-0", "desc": "Creatinine [Mass/volume] in Blood", "unit": "mg/dL", "mean": 0.95, "std": 0.2, "type": "numeric"},
        {"code": "3016-3", "desc": "Thyrotropin [Units/volume] in Serum or Plasma", "unit": "uIU/mL", "mean": 2.1, "std": 0.9, "type": "numeric"},
    ]

    patients_rows = []
    encounters_rows = []
    observations_rows = []

    first_names = ["James", "Mary", "John", "Patricia", "Robert", "Jennifer", "Michael", "Linda", "William", "Elizabeth",
                   "David", "Barbara", "Richard", "Susan", "Joseph", "Jessica", "Thomas", "Sarah", "Charles", "Karen"]
    last_names = ["Smith", "Johnson", "Williams", "Brown", "Jones", "Garcia", "Miller", "Davis", "Rodriguez", "Martinez",
                  "Hernandez", "Lopez", "Gonzalez", "Wilson", "Anderson", "Thomas", "Taylor", "Moore", "Jackson", "Martin"]

    encounter_dates_pool = [
        ["2021-03-15T09:00:00Z", "2021-11-20T10:15:00Z", "2022-06-10T08:30:00Z", "2023-01-18T11:00:00Z", "2023-09-22T09:45:00Z", "2024-04-05T08:00:00Z"],
        ["2021-05-12T08:45:00Z", "2022-01-14T09:30:00Z", "2022-10-05T10:00:00Z", "2023-05-19T08:15:00Z", "2024-02-11T11:20:00Z"],
        ["2021-02-28T10:00:00Z", "2021-09-15T09:15:00Z", "2022-04-20T11:30:00Z", "2023-03-10T08:45:00Z", "2023-11-05T10:15:00Z", "2024-05-18T09:00:00Z"],
        ["2022-02-10T09:00:00Z", "2022-08-14T10:30:00Z", "2023-02-22T08:45:00Z", "2023-09-18T09:15:00Z", "2024-03-30T10:00:00Z"],
    ]

    for p_idx in range(1, n_patients + 1):
        p_id = str(uuid.UUID(int=p_idx))
        gender = "M" if p_idx % 2 == 0 else "F"
        first = random.choice(first_names)
        last = random.choice(last_names)
        birth = f"{1950 + (p_idx % 45):04d}-{(p_idx % 12) + 1:02d}-{(p_idx % 28) + 1:02d}"

        patients_rows.append({
            "Id": p_id,
            "BIRTHDATE": birth,
            "DEATHDATE": "",
            "FIRST": first,
            "LAST": last,
            "GENDER": gender,
            "RACE": "white" if p_idx % 3 != 0 else "asian",
            "ETHNICITY": "nonhispanic",
        })

        enc_dates = encounter_dates_pool[p_idx % len(encounter_dates_pool)]

        # Individual patient trend factor for longitudinal trajectory simulation
        trend_factor = random.choice([1.08, 0.94, 1.0, 1.15, 0.90])

        for enc_idx, enc_date in enumerate(enc_dates):
            enc_id = str(uuid.uuid4())
            encounters_rows.append({
                "Id": enc_id,
                "START": enc_date,
                "STOP": enc_date,
                "PATIENT": p_id,
                "ENCOUNTERCLASS": "wellness" if enc_idx % 2 == 0 else "ambulatory",
                "CODE": "185349003",
                "DESCRIPTION": "Encounter for check up",
            })

            # Record lab panel for encounter
            # Select 6-10 labs per encounter
            encounter_labs = lab_definitions[:8] if p_idx % 2 == 0 else lab_definitions[2:]
            for lab in encounter_labs:
                base_val = lab["mean"] + random.gauss(0, lab["std"] * 0.4)
                # Apply longitudinal drift across encounters
                progression = (trend_factor ** enc_idx)
                final_val = base_val * progression

                if lab["unit"] in ("g/dL", "%", "uIU/mL", "mg/dL") and lab["mean"] < 20:
                    val_str = f"{max(0.1, final_val):.2f}"
                else:
                    val_str = f"{max(1.0, final_val):.1f}"

                observations_rows.append({
                    "DATE": enc_date,
                    "PATIENT": p_id,
                    "ENCOUNTER": enc_id,
                    "CODE": lab["code"],
                    "DESCRIPTION": lab["desc"],
                    "VALUE": val_str,
                    "UNITS": lab["unit"],
                    "TYPE": lab["type"],
                })

    # Write patients.csv
    with open(patients_file, mode="w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["Id", "BIRTHDATE", "DEATHDATE", "FIRST", "LAST", "GENDER", "RACE", "ETHNICITY"])
        writer.writeheader()
        writer.writerows(patients_rows)

    # Write encounters.csv
    with open(encounters_file, mode="w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["Id", "START", "STOP", "PATIENT", "ENCOUNTERCLASS", "CODE", "DESCRIPTION"])
        writer.writeheader()
        writer.writerows(encounters_rows)

    # Write observations.csv
    with open(observations_file, mode="w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["DATE", "PATIENT", "ENCOUNTER", "CODE", "DESCRIPTION", "VALUE", "UNITS", "TYPE"])
        writer.writeheader()
        writer.writerows(observations_rows)

    print(f"Generated Synthea sample: {len(patients_rows)} patients, {len(encounters_rows)} encounters, {len(observations_rows)} observations at {output_dir}")


if __name__ == "__main__":
    out = Path("datasets/clinical/synthea/sample")
